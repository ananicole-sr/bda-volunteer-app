/**
 * UUID v4 para client_request_id / event_id. Genera uno nuevo por cada
 * intento NUEVO del usuario y reusa el mismo en los reintentos de red.
 * Usa crypto.getRandomValues cuando existe; si no (algunos runtimes de RN),
 * cae a Math.random: solo es un id de idempotencia por voluntario, no un secreto.
 */
export function createRequestId(): string {
  const bytes = new Uint8Array(16);
  const c = (globalThis as { crypto?: { getRandomValues?: (a: Uint8Array) => Uint8Array } }).crypto;
  if (c?.getRandomValues) {
    c.getRandomValues(bytes);
  } else {
    for (let i = 0; i < 16; i++) bytes[i] = Math.floor(Math.random() * 256);
  }
  bytes[6] = (bytes[6] & 0x0f) | 0x40; // version 4
  bytes[8] = (bytes[8] & 0x3f) | 0x80; // variant RFC 4122
  const hex = Array.from(bytes, (b) => b.toString(16).padStart(2, '0')).join('');
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
}
